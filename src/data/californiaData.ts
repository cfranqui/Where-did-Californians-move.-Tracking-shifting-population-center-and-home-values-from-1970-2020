export interface CountyData {
  id: string;
  name: string;
  fips: string;
  region: 'Bay Area' | 'Southern Coast' | 'Inland Empire' | 'Central Valley' | 'Central Coast' | 'Sierra & Foothills' | 'Northern California';
  isBayArea: boolean;
  isLA: boolean;
  pop1970: number;
  pop1980: number;
  pop1990: number;
  pop2000: number;
  pop2010: number;
  pop2020: number;
  popGrowthPct: number; // 1970-2020
  homeValue1990Raw: number;
  homeValue1990Adj2020: number; // STF3 NH61A adjusted to 2020 via BLS CPI (~2.02x)
  homeValue2020: number; // 2016-2020 ACS B25077
  homeValueGrowthPct: number; // Growth from 1990 adjusted to 2020
  lat: number;
  lng: number;
  svgPath?: string;
  mapX: number; // normalized 0-100 x coordinate for CA map projection
  mapY: number; // normalized 0-100 y coordinate for CA map projection
}

